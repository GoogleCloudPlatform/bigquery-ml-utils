import importlib.metadata
import pathlib
import re
import sys
from typing import Any

_EVENTS_TABLE_PLACEHOLDER = "YOUR_EVENTS_TABLE"
_PLACEHOLDER_TABLE_ID = "__EVENTS_PROJECT__.__EVENTS_DATASET__.__EVENTS_TABLE__"
_LOOKBACK_CLAUSE = "timestamp >= TIMESTAMP_SUB(start_ts, INTERVAL 7 DAY)"

